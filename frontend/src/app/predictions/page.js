"use client";

import { useState, useEffect, useCallback } from "react";
import {
  getPredictions,
  getPredictionStats,
} from "@/lib/api";
import {
  Search,
  Filter,
  CheckCircle,
  AlertTriangle,
  Clock,
  ArrowUpDown,
  ChevronLeft,
  ChevronRight,
  TrendingUp,
} from "lucide-react";

export default function PredictionsPage() {
  const [predictions, setPredictions] = useState([]);
  const [stats, setStats] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  // Filters & Pagination
  const [page, setPage] = useState(1);
  const [pageSize, setPageSize] = useState(25);
  const [delayStatus, setDelayStatus] = useState("");
  const [search, setSearch] = useState("");
  const [sortBy, setSortBy] = useState("id");
  const [sortOrder, setSortOrder] = useState("desc");
  const [totalPages, setTotalPages] = useState(1);
  const [totalCount, setTotalCount] = useState(0);

  useEffect(() => {
    let isMounted = true;
    async function loadData() {
      setLoading(true);
      setError(null);
      try {
        const [predData, statsData] = await Promise.all([
          getPredictions({
            page,
            pageSize,
            delayStatus,
            search,
            sortBy,
            sortOrder,
          }),
          getPredictionStats(),
        ]);

        if (isMounted) {
          setPredictions(predData.items || []);
          setTotalPages(predData.total_pages || 1);
          setTotalCount(predData.total || 0);
          setStats(statsData);
        }
      } catch (err) {
        if (isMounted) setError(err.message || "Failed to load predictions");
      } finally {
        if (isMounted) setLoading(false);
      }
    }

    loadData();
    return () => {
      isMounted = false;
    };
  }, [page, pageSize, delayStatus, search, sortBy, sortOrder]);

  const toggleSort = (field) => {
    if (sortBy === field) {
      setSortOrder(sortOrder === "asc" ? "desc" : "asc");
    } else {
      setSortBy(field);
      setSortOrder("desc");
    }
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <h1 className="text-2xl font-bold tracking-tight" style={{ color: "var(--text-primary)" }}>
          Ride Order Predictions
        </h1>
        <p className="text-sm mt-1" style={{ color: "var(--text-secondary)" }}>
          Historical ETA predictions &amp; delay classifications generated by PyTorch engine
        </p>
      </div>

      {/* Stats Overview */}
      {stats && (
        <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
          <div className="enterprise-card p-6">
            <div className="flex items-center justify-between" style={{ color: "var(--text-secondary)" }}>
              <span className="text-xs font-semibold uppercase tracking-wider">Total Predictions</span>
              <Clock className="w-4 h-4" style={{ color: "var(--accent-indigo)" }} />
            </div>
            <p className="text-2xl font-bold mt-2" style={{ color: "var(--text-primary)" }}>
              {stats.total_predictions?.toLocaleString()}
            </p>
            <p className="text-xs mt-1" style={{ color: "var(--text-muted)" }}>Evaluated on test dataset</p>
          </div>

          <div className="enterprise-card p-6">
            <div className="flex items-center justify-between" style={{ color: "var(--text-secondary)" }}>
              <span className="text-xs font-semibold uppercase tracking-wider">Avg ETA Error</span>
              <TrendingUp className="w-4 h-4" style={{ color: "var(--accent-blue)" }} />
            </div>
            <p className="text-2xl font-bold mt-2" style={{ color: "var(--text-primary)" }}>
              {stats.avg_eta_error !== null ? `${stats.avg_eta_error} min` : "N/A"}
            </p>
            <p className="text-xs mt-1" style={{ color: "var(--text-muted)" }}>Mean absolute error (MAE)</p>
          </div>

          <div className="enterprise-card p-6">
            <div className="flex items-center justify-between" style={{ color: "var(--text-secondary)" }}>
              <span className="text-xs font-semibold uppercase tracking-wider">Predicted Delayed</span>
              <AlertTriangle className="w-4 h-4" style={{ color: "var(--accent-rose)" }} />
            </div>
            <p className="text-2xl font-bold mt-2" style={{ color: "var(--accent-rose)" }}>
              {stats.total_delayed?.toLocaleString()}
            </p>
            <p className="text-xs mt-1" style={{ color: "var(--text-muted)" }}>
              {stats.total_predictions
                ? `${((stats.total_delayed / stats.total_predictions) * 100).toFixed(1)}% of total`
                : "0%"}
            </p>
          </div>

          <div className="enterprise-card p-6">
            <div className="flex items-center justify-between" style={{ color: "var(--text-secondary)" }}>
              <span className="text-xs font-semibold uppercase tracking-wider">Predicted On-Time</span>
              <CheckCircle className="w-4 h-4" style={{ color: "var(--accent-emerald)" }} />
            </div>
            <p className="text-2xl font-bold mt-2" style={{ color: "var(--accent-emerald)" }}>
              {stats.total_on_time?.toLocaleString()}
            </p>
            <p className="text-xs mt-1" style={{ color: "var(--text-muted)" }}>
              {stats.total_predictions
                ? `${((stats.total_on_time / stats.total_predictions) * 100).toFixed(1)}% of total`
                : "0%"}
            </p>
          </div>
        </div>
      )}

      {/* Filter Controls */}
      <div className="enterprise-card p-4 flex flex-col md:flex-row gap-4 items-center justify-between">
        {/* Search */}
        <div className="relative w-full md:w-80">
          <Search className="absolute left-3 top-2.5 w-4 h-4" style={{ color: "var(--text-muted)" }} />
          <input
            type="text"
            placeholder="Search Order ID..."
            value={search}
            onChange={(e) => {
              setSearch(e.target.value);
              setPage(1);
            }}
            className="w-full pl-9 pr-4 py-2 text-sm"
          />
        </div>

        <div className="flex flex-wrap items-center gap-3 w-full md:w-auto">
          {/* Status Filter Buttons */}
          <div className="flex items-center space-x-1 p-1 rounded-xl" style={{ background: "var(--bg-main)", border: "1px solid var(--border-main)" }}>
            <button
              onClick={() => {
                setDelayStatus("");
                setPage(1);
              }}
              style={
                delayStatus === ""
                  ? { background: "var(--accent-indigo)", color: "#FFFFFF" }
                  : { color: "var(--text-secondary)" }
              }
              className="px-3 py-1.5 text-xs font-semibold rounded-lg transition-colors"
            >
              All
            </button>
            <button
              onClick={() => {
                setDelayStatus("delayed");
                setPage(1);
              }}
              style={
                delayStatus === "delayed"
                  ? { background: "var(--accent-indigo)", color: "#FFFFFF" }
                  : { color: "var(--text-secondary)" }
              }
              className="px-3 py-1.5 text-xs font-semibold rounded-lg transition-colors"
            >
              Delayed
            </button>
            <button
              onClick={() => {
                setDelayStatus("on_time");
                setPage(1);
              }}
              style={
                delayStatus === "on_time"
                  ? { background: "var(--accent-indigo)", color: "#FFFFFF" }
                  : { color: "var(--text-secondary)" }
              }
              className="px-3 py-1.5 text-xs font-semibold rounded-lg transition-colors"
            >
              On-Time
            </button>
          </div>

          {/* Page Size Select */}
          <select
            value={pageSize}
            onChange={(e) => {
              setPageSize(Number(e.target.value));
              setPage(1);
            }}
            className="px-3 py-2 text-xs font-medium"
          >
            <option value={15}>15 per page</option>
            <option value={25}>25 per page</option>
            <option value={50}>50 per page</option>
            <option value={100}>100 per page</option>
          </select>
        </div>
      </div>

      {/* Error Message */}
      {error && (
        <div className="p-4 badge-danger rounded-xl text-sm">
          {error}
        </div>
      )}

      {/* Predictions Table */}
      <div className="enterprise-card overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead>
              <tr>
                <th
                  onClick={() => toggleSort("order_id")}
                  className="px-4 py-3.5 cursor-pointer hover:opacity-80 transition-opacity"
                >
                  <div className="flex items-center space-x-1">
                    <span>Order ID</span>
                    <ArrowUpDown className="w-3 h-3" />
                  </div>
                </th>
                <th className="px-4 py-3.5">Booking Timestamp</th>
                <th
                  onClick={() => toggleSort("actual_total_time_minutes")}
                  className="px-4 py-3.5 cursor-pointer hover:opacity-80 transition-opacity"
                >
                  Actual ETA
                </th>
                <th className="px-4 py-3.5">Google ETA</th>
                <th
                  onClick={() => toggleSort("predicted_eta_minutes")}
                  className="px-4 py-3.5 cursor-pointer hover:opacity-80 transition-opacity"
                >
                  Model Predicted ETA
                </th>
                <th className="px-4 py-3.5">ETA Error</th>
                <th
                  onClick={() => toggleSort("predicted_delay_probability")}
                  className="px-4 py-3.5 cursor-pointer hover:opacity-80 transition-opacity"
                >
                  Delay Probability
                </th>
                <th className="px-4 py-3.5 text-center">Prediction</th>
                <th className="px-4 py-3.5 text-center">Ground Truth</th>
              </tr>
            </thead>
            <tbody className="divide-y" style={{ borderColor: "var(--border-main)" }}>
              {loading ? (
                Array.from({ length: 8 }).map((_, idx) => (
                  <tr key={idx} className="animate-pulse">
                    <td className="px-4 py-4"><div className="h-4 rounded w-24" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4"><div className="h-4 rounded w-32" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4"><div className="h-4 rounded w-16" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4"><div className="h-4 rounded w-16" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4"><div className="h-4 rounded w-16" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4"><div className="h-4 rounded w-16" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4"><div className="h-4 rounded w-20" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4 text-center"><div className="h-6 rounded-full w-16 mx-auto" style={{ background: "var(--bg-hover)" }}></div></td>
                    <td className="px-4 py-4 text-center"><div className="h-6 rounded-full w-16 mx-auto" style={{ background: "var(--bg-hover)" }}></div></td>
                  </tr>
                ))
              ) : predictions.length === 0 ? (
                <tr>
                  <td colSpan={9} className="text-center py-12" style={{ color: "var(--text-muted)" }}>
                    No predictions found. Run predictions or upload test data.
                  </td>
                </tr>
              ) : (
                predictions.map((row) => {
                  const errorMin = row.predicted_eta_minutes && row.actual_total_time_minutes
                    ? Math.abs(row.predicted_eta_minutes - row.actual_total_time_minutes).toFixed(2)
                    : "N/A";
                  const probPercent = row.predicted_delay_probability !== null
                    ? (row.predicted_delay_probability * 100).toFixed(1)
                    : "0.0";

                  const isMatch = row.predicted_delay === row.order_delayed;

                  return (
                    <tr
                      key={row.id}
                      className="font-mono text-xs"
                    >
                      <td className="px-4 py-3.5 font-bold" style={{ color: "var(--text-primary)" }}>{row.order_id}</td>
                      <td className="px-4 py-3.5 font-sans text-xs" style={{ color: "var(--text-secondary)" }}>{row.booking_timestamp || "-"}</td>
                      <td className="px-4 py-3.5 font-bold" style={{ color: "var(--text-primary)" }}>
                        {row.actual_total_time_minutes?.toFixed(1)} min
                      </td>
                      <td className="px-4 py-3.5" style={{ color: "var(--text-secondary)" }}>
                        {row.google_total_eta_minutes?.toFixed(1)} min
                      </td>
                      <td className="px-4 py-3.5 font-bold" style={{ color: "var(--text-primary)" }}>
                        {row.predicted_eta_minutes?.toFixed(1)} min
                      </td>
                      <td className="px-4 py-3.5">
                        <span className={
                          Number(errorMin) <= 3.0
                            ? "badge-success"
                            : Number(errorMin) <= 7.0
                            ? "badge-warning"
                            : "badge-danger"
                        }>
                          ±{errorMin}m
                        </span>
                      </td>
                      <td className="px-4 py-3.5">
                        <div className="flex items-center space-x-2">
                          <div className="w-16 rounded-full h-1.5 overflow-hidden" style={{ background: "var(--bg-hover)" }}>
                            <div
                              className="h-full rounded-full"
                              style={{
                                width: `${Math.min(100, probPercent)}%`,
                                backgroundColor: row.predicted_delay_probability >= 0.5
                                  ? "var(--accent-rose)"
                                  : row.predicted_delay_probability >= 0.3
                                  ? "var(--accent-amber)"
                                  : "var(--accent-emerald)"
                              }}
                            ></div>
                          </div>
                          <span className="font-bold">{probPercent}%</span>
                        </div>
                      </td>
                      <td className="px-4 py-3.5 text-center">
                        <span
                          className={`inline-flex items-center font-sans ${
                            row.predicted_delay === 1 ? "badge-danger" : "badge-success"
                          }`}
                        >
                          {row.predicted_delay === 1 ? "Delayed" : "On Time"}
                        </span>
                      </td>
                      <td className="px-4 py-3.5 text-center">
                        <span
                          className={`inline-flex items-center px-2 py-0.5 rounded text-[11px] font-sans ${
                            isMatch
                              ? "text-[var(--text-muted)]"
                              : "badge-warning"
                          }`}
                        >
                          {row.order_delayed === 1 ? "Delayed" : "On Time"}
                          {!isMatch && <span className="ml-1 text-[10px]">⚠️</span>}
                        </span>
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination Footer */}
        <div className="p-4 flex flex-col sm:flex-row items-center justify-between gap-4 text-xs" style={{ background: "var(--bg-sidebar)", borderTop: "1px solid var(--border-main)", color: "var(--text-secondary)" }}>
          <div>
            Showing <span className="font-bold" style={{ color: "var(--text-primary)" }}>{predictions.length}</span> of{" "}
            <span className="font-bold" style={{ color: "var(--text-primary)" }}>{totalCount.toLocaleString()}</span> predictions
          </div>
          <div className="flex items-center space-x-2">
            <button
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              disabled={page === 1 || loading}
              className="p-1.5 btn-secondary disabled:opacity-40 disabled:cursor-not-allowed rounded-lg"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>
            <span className="px-3 py-1 font-semibold rounded-lg" style={{ background: "var(--bg-card)", border: "1px solid var(--border-main)", color: "var(--text-primary)" }}>
              Page {page} of {totalPages}
            </span>
            <button
              onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
              disabled={page >= totalPages || loading}
              className="p-1.5 btn-secondary disabled:opacity-40 disabled:cursor-not-allowed rounded-lg"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
